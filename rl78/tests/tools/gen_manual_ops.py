#!/usr/bin/env python3
"""Generate tests/manual_ops.inc from the Renesas RL78 software manual.

Usage: gen_manual_ops.py MANUAL_TEXT > manual_ops.inc

MANUAL_TEXT is the plain text of R01US0015 (Rev.2.40) extracted page by page
with "=====PAGE n=====" separators (e.g. with macOS PDFKit).  The manual
itself is not stored in this repository.  The script reads the operation
lists (Tables 5-5, 5-6, 5-7: one row per instruction form) and emits
{core, mnemonic, operands, bytes, clocks(note1), clocks(note2)} rows.
"""
import re
import sys

MN = set('MOV XCH ONEB CLRB MOVS MOVW XCHW ONEW CLRW ADD ADDC SUB SUBC AND OR XOR CMP '
         'CMP0 CMPS ADDW SUBW CMPW MULU MULHU MULH DIVHU DIVWU MACHU MACH INC DEC INCW '
         'DECW SHR SHRW SHL SHLW SAR SARW ROR ROL RORC ROLC ROLWC MOV1 AND1 OR1 XOR1 SET1 '
         'CLR1 NOT1 CALL CALLT BRK RET RETI RETB PUSH POP BR BC BNC BZ BNZ BH BNH BT BF '
         'BTCLR SKC SKNC SKZ SKNZ SKH SKNH SEL NOP EI DI HALT STOP'.split())
ROW = re.compile(r'^(.*?)\s+(\d)\s+(\d+(?:/\d+)?)\s+(—|\d+(?:/\d+)?)\s+(?![—\d])(.*)$')


def main():
    txt = open(sys.argv[1], encoding='utf-8').read()
    parts = re.split(r'=====PAGE (\d+)=====\n', txt)
    pages = {int(parts[i]): parts[i + 1] for i in range(1, len(parts), 2)}
    out = []
    cur = None
    for p in sorted(pages):
        t = pages[p]
        m = re.search(r'Operation List of RL78-(S\d) Core', t)
        if not m:
            continue
        core = m.group(1)
        if 'Table 5 - 7' in t:      # page header typo "S2" inside the S3 table
            core = 'S3'
        t = re.sub(r'\nNote 3\n', ' ', t)
        t = t.replace('XCH A, rNote 3 1 (r = X)\n2 (other\nthan r = X)\n1 — A ←→ r',
                      'XCH A, r 1 1 — A ←→ r')
        for line in t.split('\n'):
            line = line.strip()
            for pre in ('Shift ', 'Rotate ', 'CPU control ', 'Stack ', 'Call and ', 'Multiply '):
                if line.startswith(pre):
                    line = line[len(pre):]
            line = re.sub(r'Note\s*\d', '', line)
            mm = ROW.match(line)
            if not mm:
                continue
            head = mm.group(1).split()
            if not head:
                continue
            if head[0] in MN and (head[0] != 'BC' or (len(head) > 1 and head[1].startswith('$'))):
                cur = head[0]
                head = head[1:]
            op = ' '.join(head)
            if op == '—':
                op = ''
            out.append((core, cur, op, mm.group(2), mm.group(3), mm.group(4)))
    print('/* Generated by tests/tools/gen_manual_ops.py from R01US0015 Rev.2.40,')
    print('   Tables 5-5 (S1), 5-6 (S2), 5-7 (S3).  Do not edit. */')
    for core, mn, op, b, c1, c2 in out:
        c2 = '' if c2 == '—' else c2
        print('{%s, "%s", "%s", %s, "%s", "%s"},' % (core[1], mn, op, b, c1, c2))


if __name__ == '__main__':
    main()
